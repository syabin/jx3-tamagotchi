# ---- 图案定义：三引号，每行自动补齐到 16 字符，超过 16 直接报错 ----
ART = {}
def add(sid, art, pal=None):
    if isinstance(art, list):
        lines = list(art)
    else:
        lines = [ln for ln in art.strip("\n").split("\n")]
    if len(lines) != 16:
        raise ValueError("%s: need 16 rows, got %d" % (sid, len(lines)))
    rows = []
    for i, ln in enumerate(lines):
        ln = ln.rstrip()
        if len(ln) > 16:
            raise ValueError("%s row %d: too long (%d)" % (sid, i, len(ln)))
        rows.append(ln.ljust(16, "."))
    ART[sid] = {"r": rows, "p": pal or {}}

