def rgb565(h):
    r = int(h[1:3], 16) >> 3
    g = int(h[3:5], 16) >> 2
    b = int(h[5:7], 16) >> 3
    return (r << 11) | (g << 5) | b


def flat(sid, over=None):
    sp = ART[sid]
    pal = dict(PAL)
    pal.update(sp["p"])
    if over:
        pal.update(over)
    vals = []
    for row in sp["r"]:
        for ch in row:
            h = pal.get(ch)
            vals.append(0 if not h else rgb565(h))
    assert len(vals) == 256
    return vals


